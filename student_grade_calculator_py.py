# Student Grade Calculator

def calculate_grade(percentage):
    if percentage >= 90:
        return "A+"
    elif percentage >= 80:
        return "A"
    elif percentage >= 70:
        return "B"
    elif percentage >= 60:
        return "C"
    elif percentage >= 40:
        return "D"
    else:
        return "Fail"


print("================================")
print("     STUDENT GRADE CALCULATOR")
print("================================")

name = input("Enter student name: ")

marks = []

for i in range(1, 6):
    while True:
        try:
            mark = float(input(f"Enter marks for subject {i}: "))
            if 0 <= mark <= 100:
                marks.append(mark)
                break
            else:
                print("Please enter marks between 0 and 100.")
        except ValueError:
            print("Please enter a valid number.")

total = sum(marks)
percentage = total / 5
grade = calculate_grade(percentage)

print("\n========== RESULT ==========")
print("Student Name:", name)
print("Total Marks:", total, "/ 500")
print("Percentage:", round(percentage, 2), "%")
print("Grade:", grade)

if percentage >= 40:
    print("Result: PASS")
else:
    print("Result: FAIL")

print("============================")